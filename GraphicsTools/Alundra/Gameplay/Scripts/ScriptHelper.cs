    public static int SignExtendWord(int i)
    {
        if ((i & 0x8000) == 0)
        {
            return 0x0000FFFF & i;
        }

        return (int)(0xFFFF0000 | i);
    }

    public static int DirFromVector(int x, int y)
    {
        var flipper = 0;
        if (y < 1)
        {
            flipper = 2;
        }

        if (x < 0)
        {
            flipper++;
        }

        if (x < 0)
        {
            x = -x;
        }

        if (y < 0)
        {
            y = -y;
        }

        var greatest = x;
        if (x < y)
        {
            y = greatest;
        }

        var div = 0;
        var val = DivTable[div];
        if (val < greatest)
        {
            do
            {
                div++;
                val = DivTable[div];
            } while (val < greatest);
        }
        x = x >> div;
        y = y >> div;

        var direction = (int)DirectionTable[y * 16 + x];

        var ret = direction;
        if (flipper == 1)
        {
            ret = 8 - direction;
        }
        else if (flipper == 2)
        {
            ret = 0x18 - direction;
        }
        else if (flipper == 3)
        {
            ret = 8 + direction;
        }
        else if (flipper == 0)
        {
            ret = 0x18 + direction;
        }

        return ret & 0x1f;
    }

