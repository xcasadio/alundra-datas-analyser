for idx, addr_int in enumerate(address_list):
    address = toAddr(addr_int)
    function = getFunctionAt(address)

    if function is None:
        print("[!] No function at {}".format(address))
        continue

    current_name = function.getName()
    if not (current_name.startswith("Script_FUN") or current_name.startswith("Script_0x")):
        print("[=] Skipping {} at {} (does not start with Script_FUN or Script_0x)".format(current_name, address))
        continue

    new_name = "Script_{}_{}".format(idx, format(idx, "03X"))
    try:
        function.setName(new_name, SourceType.USER_DEFINED)
        print("[+] Renamed {} from {} to {}".format(address, current_name, new_name))
    except Exception as e:
        print("[!] Failed to rename at {}: {}".format(address, str(e)))